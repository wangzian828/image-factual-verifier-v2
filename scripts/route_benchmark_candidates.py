from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Dict, List


DEFAULT_REAL_THRESHOLD = 55
DEFAULT_SYNTHETIC_THRESHOLD = 55


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Route scored source materials into benchmark candidate buckets."
    )
    parser.add_argument(
        "--input-manifest",
        default="data/source_materials/recent_diverse_scored_all/scored_manifest.jsonl",
        help="Scored manifest generated by score_source_materials_with_gemini.py",
    )
    parser.add_argument(
        "--output-dir",
        default="data/benchmark_candidates/recent_diverse",
        help="Directory to store routed candidate files.",
    )
    parser.add_argument(
        "--real-threshold",
        type=int,
        default=DEFAULT_REAL_THRESHOLD,
        help="Minimum image_information_score for real_photo_candidate.",
    )
    parser.add_argument(
        "--synthetic-threshold",
        type=int,
        default=DEFAULT_SYNTHETIC_THRESHOLD,
        help="Minimum synthetic_real_potential for synthetic_real_candidate.",
    )
    return parser.parse_args()


def _load_rows(path: Path) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            rows.append(json.loads(line))
    return rows


def _write_jsonl(path: Path, rows: List[Dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")


def route_candidates(
    input_manifest: Path,
    output_dir: Path,
    *,
    real_threshold: int,
    synthetic_threshold: int,
) -> Dict[str, Any]:
    rows = _load_rows(input_manifest)

    real_rows: List[Dict[str, Any]] = []
    synthetic_rows: List[Dict[str, Any]] = []
    discard_rows: List[Dict[str, Any]] = []

    for row in rows:
        image_score = int(row.get("image_information_score", 0) or 0)
        synthetic_score = int(row.get("synthetic_real_potential", 0) or 0)

        if image_score >= real_threshold:
            routed = "real_photo_candidate"
            real_rows.append({**row, "routed_bucket": routed})
            continue

        if synthetic_score >= synthetic_threshold:
            routed = "synthetic_real_candidate"
            synthetic_rows.append({**row, "routed_bucket": routed})
            continue

        routed = "discard_low_signal"
        discard_rows.append({**row, "routed_bucket": routed})

    real_path = output_dir / "real_photo_candidates.jsonl"
    synthetic_path = output_dir / "synthetic_real_candidates.jsonl"
    discard_path = output_dir / "discarded_low_signal.jsonl"
    summary_path = output_dir / "summary.json"

    _write_jsonl(real_path, real_rows)
    _write_jsonl(synthetic_path, synthetic_rows)
    _write_jsonl(discard_path, discard_rows)

    summary = {
        "input_manifest": str(input_manifest),
        "output_dir": str(output_dir),
        "real_threshold": real_threshold,
        "synthetic_threshold": synthetic_threshold,
        "num_rows": len(rows),
        "real_photo_candidates": len(real_rows),
        "synthetic_real_candidates": len(synthetic_rows),
        "discarded_low_signal": len(discard_rows),
        "real_path": str(real_path),
        "synthetic_path": str(synthetic_path),
        "discard_path": str(discard_path),
    }
    summary_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    return summary


def main() -> None:
    args = _parse_args()
    report = route_candidates(
        Path(args.input_manifest),
        Path(args.output_dir),
        real_threshold=args.real_threshold,
        synthetic_threshold=args.synthetic_threshold,
    )
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
